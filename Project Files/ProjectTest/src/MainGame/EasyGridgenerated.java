    public EasyGridgenerated() {
        initComponents();

        BasePnl.setLayout(new GridLayout(rows, columns));
        //Add the buttons to the panel's gridLayout 
        buttons = new JButton[rows][columns];
        for (int i = 0; i < rows; i++) {
            for (int j = 0; j < columns; j++) {
                JButton btn = new JButton();
                //Variables to enable use of i and j (may not be needed to pass 
                //i and j into a subroutine as parameters 
                int x = i;
                int y = j;
                //add an action listener for each button that is created 
                btn.addActionListener(new ActionListener() {
                    @Override
                    public void actionPerformed(ActionEvent e) {
                        System.out.println("Button clicked at: row " + x
                                + " column " + y);
                        if (game_in_progress == false) {
                            placeMines();
                            game_in_progress = true;
                            displayMines();//Testing
                            System.out.println("Mines placed");
                        }
                        //check to see if this location has a mine (if true) 
                        if (buttonsAsMines[x][y]) {
                            gameLoss();//to be changed to gameLossScreen()
                        //if index has no mine call grid-clearing function
                        } else {
                            gridClear();
                        }
                    }
                });
                buttons[i][j] = btn;
                BasePnl.add(btn);
            }
        }
    }

