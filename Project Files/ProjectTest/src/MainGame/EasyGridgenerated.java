    //subroutine to update buttonsAsMines to contain the position of mines
    private void placeMines() {
        //Initialisation 
        int positionX;
        int positionY;
        int mines = 0;
        /*loop to iterate while the number of mines placed in the 2D array for 
        the grid is less than totalMineCount*/
        while (mines < totalMineCount) {
            //Generate a random x and y coordinate
            positionX = (int) (Math.random() * 10);
            positionY = (int) (Math.random() * 10);
            //if this position does not already have a mine, place a mine there
            if (!buttonsAsMines[positionX][positionY]) {
                buttonsAsMines[positionX][positionY] = true;
                //increment 
                mines += 1;
            }
        }
    }

    private void gameLoss() {
        //game_in_progress = false;
        System.out.println("YOU LOSE");
    }

    private void gridClear() {
        System.out.println("GridCleared");
    }
    private void displayMines(){
        //iterate through 2D array of mine locations 
        for (int i = 0; i < rows; i++) {
            for (int j = 0; j < columns; j++) {
                //if a mine is found, change the colour of button at this index
                if(buttonsAsMines[i][j]){
                    //change colour of button
                    buttons[i][j].setBackground(java.awt.Color.cyan);;
                }
            }
            
        }
    }
