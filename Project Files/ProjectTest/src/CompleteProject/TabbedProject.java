    private void revealGridNumbers() {
        //iterate through each button in the grid
        //the index of each button is given by [rows][columns]
        for (int rows = 0; rows < buttons.length; rows++) {
            for (int columns = 0; columns < buttons[rows].length; columns++) {
                //if any of of the contained statments are true the if will execute 
                /*
                If a tile is clear and any of the 8 tiles around it are not clear 
                then the number of mines around it should be displayed  
                 */
                //if a tile is cleared, move on to check the surrounding tiles 
                if (buttons_cleared[rows][columns] == true) {

                    if ((inBounds(rows - 1, columns - 1) && buttons_cleared[rows - 1][columns - 1] == false)
                            ||//above left
                            (inBounds(rows - 1, columns) && buttons_cleared[rows - 1][columns] == false)
                            ||//above 
                            (inBounds(rows - 1, columns + 1) && buttons_cleared[rows - 1][columns + 1] == false)
                            ||//above right
                            (inBounds(rows, columns - 1) && buttons_cleared[rows][columns - 1] == false)
                            ||//left
                            (inBounds(rows, columns + 1) && buttons_cleared[rows][columns + 1] == false)
                            ||//right
                            (inBounds(rows + 1, columns - 1) && buttons_cleared[rows + 1][columns - 1] == false)
                            ||//below left
                            (inBounds(rows + 1, columns) && buttons_cleared[rows + 1][columns] == false)
                            ||//below middle
                            (inBounds(rows + 1, columns + 1) && buttons_cleared[rows + 1][columns + 1] == false) //below right
                            ) {
                        buttons[rows][columns].setText(Integer.toString(buttons_As_Mines[rows][columns]));
                    }
                }
            }
        }
    }

