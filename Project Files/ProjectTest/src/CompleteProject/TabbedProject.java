    private void generateGrid() throws IOException {
        //clear the grid from the previous game
        GameGridPnl.removeAll();
        GameGridPnl.setLayout(new GridLayout(rows, columns));
        GameGridPnl.setSize(400, 400);
        //Add the buttons to the panel's gridLayout 
        buttons = new JButton[rows][columns];
        //Repeat rows*columns number of times 
        for (int r = 0; r < rows; r++) {
            for (int c = 0; c < columns; c++) {
                JButton btn = new JButton();
                /*row and col are temporary variables needed to use the values 
                of r and c within the action listener subroutine */
                int row = r;
                int col = c;
                //add an action listener for each button that is created 
                btn.addActionListener(new ActionListener() {
                    @Override
                    public void actionPerformed(ActionEvent e) {
                        if (!btn.getText().equals("⚑")) {
                            //If this is the first button clicked, start the game
                            if (game_in_progress == false) {
                                placeMines(row, col);
                                gridClear(row, col);
                                game_in_progress = true;
                            }
                            //check to see if this location has a mine 
                            if (buttons_As_Mines[row][col] == -1) {
                                gameLoss();
                            } else {
                                gridClear(row, col);
                                //Check whether the user has cleared the grid fully
                                gameSuccessful();
                            }
                            //Show the relevant mine numbers to the user
                            revealGridNumbers();
                        }
                    }

                });
                btn.addMouseListener(new MouseAdapter() {
                    @Override
                    public void mouseClicked(MouseEvent m) {
                        if (SwingUtilities.isRightMouseButton(m)) {
                            if (btn.getText().equals("")) {
                                btn.setForeground(Color.RED);
                                btn.setText("⚑");
                                flagged = flagged + 1;
                            } else if (btn.getText().equals("⚑")) {
                                btn.setForeground(Color.red);
                                btn.setText("?");
                                flagged = flagged - 1;
                            }else{
                                btn.setForeground(Color.BLACK);
                                btn.setText("");
                            }
                            flagNumberfld.setText(Integer.toString(totalMineCount - flagged));
                        }
                    }
                });
                btn.setBackground(Color.GREEN);//Defualt colour
                //Add the generated button to the button array and the panel 
                buttons[r][c] = btn;
                GameGridPnl.add(btn);
                btn.setFont(new Font("Ariel", Font.PLAIN, 22));
                btn.setText("");
            }
        }
    }

