    public boolean passwordFormat(String password) {
        //define the regex of the password (its conditions for validity)
        String regex = "^(?=.*[0-9])(?=.*[@£#$%^!&-+=()]).{6,}$";
        //complie the regex and define the password
        Pattern p = Pattern.compile(regex);
        Matcher m = p.matcher(password);
        //Check if the password fits these criteria and return the result
        return m.matches();
    }

    public String getStatistic(int lineNum) {
        //declare statistics variable as null
        String statistic = "";
        String username = accountName;
        int line = 0;
        //convert lineNum to 0th indexing 
        lineNum = lineNum - 1;
        //Declare the folder being accessed and add its files to a list
        File folder = new File("P:\\Component 3\\ProjectTest\\User Files");
        File[] listOfFiles = folder.listFiles();
        //iterate through all files in the folder
        for (File file : listOfFiles) {
            //If the correct file is found
            if (file.getName().equals(username + ".txt")) {
                FileReader fileRead = null;
                try {
                    //declare scanner to read from this file
                    fileRead = new FileReader(file);
                    BufferedReader reader = new BufferedReader(fileRead);
                    while (line <= lineNum) {
                        statistic = reader.readLine();
                        line = line + 1;
                    }
                } catch (FileNotFoundException ex) {
                    Logger.getLogger(TabbedProject.class.getName()).log(Level.SEVERE, null, ex);
                } catch (IOException ex) {
                    Logger.getLogger(TabbedProject.class.getName()).log(Level.SEVERE, null, ex);
                } finally {
                    try {
                        fileRead.close();
                    } catch (IOException ex) {
                        Logger.getLogger(TabbedProject.class.getName()).log(Level.SEVERE, null, ex);
                    }
                }
            }
        }
        return statistic;
    }

