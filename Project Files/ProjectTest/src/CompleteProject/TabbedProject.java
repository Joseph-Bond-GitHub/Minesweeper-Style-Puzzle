    //subroutine to check if the grid has been fully cleared
    private void gameSuccessful() {
        //count is the number of cleared spaces in the grid 
        int count = 0;
        //total is the number of spaces in the grid (No. of rows * No. of cols)
        int total = buttons_cleared.length * buttons_cleared[0].length;
        //iterate through the indexes in the grid 
        for (int row = 0; row < buttons_cleared.length; row++) {
            for (int column = 0; column < buttons_cleared[row].length; column++) {
                //if a grid space is clear, increment count
                if (buttons_cleared[row][column] == true) {
                    count = count + 1;
                }
            }
        }
        //if the user has cleared all non-mine spaces
        if (total - count == totalMineCount) {
            game_in_progress = false;
            flagged = 0;
            try {
                //increment win statistic
                incrementStatistic(3);
            } catch (IOException ex) {
                Logger.getLogger(TabbedProject.class.getName()).log(Level.SEVERE, null, ex);
            }
            //select win screen
            BaseTabbedPnl.setSelectedIndex(6);
        }
    }

