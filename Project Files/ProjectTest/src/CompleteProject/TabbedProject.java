        //get the username and pasword
        String username = CreateNewusernameFld.getText();

        //get first password and convert from character array to string
        char[] pswrdChar = CreateNewPswrdFld1.getPassword();
        String password1 = "";
        for (char c : pswrdChar) {
            password1 = password1 + c;
        }

        //Get the second password and convert from character array to a string
        pswrdChar = CreateNewPswrdFld2.getPassword();
        String password2 = "";
        for (char c : pswrdChar) {
            password2 = password2 + c;
        }
